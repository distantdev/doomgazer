const char* presetCategory(int index)
{
    // Grouping only; the names already say what the tone is. Noise and Motion
    // are the presets that move or misbehave rather than sit on a riff.
    static const char* const kCategories[kFactoryPresetCount] = {
        "Doom",   "Doom",   "Drone",  "Doom",   "Drone",  "Drone",  "Drone",
        "Doom",   "Noise",  "Drone",  "Motion", "Motion", "Motion", "Motion",
        "Doom",   "Doom",   "Space",  "Doom",   "Drone",  "Space",  "Doom",
        "Space",  "Drone",  "Space",  "Grit",   "Grit",   "Grit",   "Space",
        "Motion", "Doom",   "Doom",   "Motion", "Grit",
    };
    if (index < 0 || index >= kFactoryPresetCount)
        return "Doom";
    return kCategories[index];
}

Parameters factoryPreset(int index)
{
    const int slot = std::max(0, std::min(kPresetSlots - 1, index));
    const int source = slot < kFactoryPresetCount ? slot : 0;
    Parameters params;
    for (int i = 1; i <= kParameterCount; ++i)
        params.at(i) = kPresetValues[source][static_cast<std::size_t>(i - 1)];
    params.presetSlot = static_cast<double>(slot);
    params.clampIntoRange();
    return params;
}

